/** Escapa comillas dobles para insertar texto dentro de un `echo "..."` de bash. */
function shEscape(text: string): string {
  return text.replace(/(["\\$`])/g, "\\$1");
}

export function buildDeployScript({
  yaml,
  toolSummaries,
  skippedTools,
  locale = "es",
}: {
  yaml: string;
  toolSummaries: StackMergeToolSummary[];
  skippedTools: string[];
  locale?: "es" | "en";
}): string {
  const t = STRINGS[locale];
  const appDir = "$HOME/altfreestack-app";

  // mergeDockerComposeFiles() antepone un comentario de cabecera que
  // literalmente menciona el texto "change-me..." como documentación — si
  // randomizeSecrets() se aplicara sobre el YAML completo, ese propio
  // comentario quedaría "aleatorizado" también (falso positivo del regex).
  // Por eso aquí se sustituye esa cabecera por una propia para el contexto
  // de despliegue en 1 comando, y solo se aleatoriza el cuerpo real
  // (services/volumes) a partir de "services:".
  const bodyStart = yaml.indexOf("services:");
  const body = bodyStart >= 0 ? yaml.slice(bodyStart) : yaml;
  const toolNames = toolSummaries.map((tool) => tool.name).join(", ");
  const finalYaml = [...t.composeHeader(toolNames), "", randomizeSecrets(body)].join("\n");
  const delimiter = pickHeredocDelimiter(finalYaml);

  const summaryLines = toolSummaries.map((tool) =>
    tool.port
      ? `echo "• ${shEscape(tool.name)}:  http://$IP:${tool.port}"`
      : `echo "• ${shEscape(tool.name)}"`
  );

  const skippedLines =
    skippedTools.length > 0
      ? [`echo ""`, `echo "${shEscape(t.notIncluded)} ${shEscape(skippedTools.join(", "))}"`]
      : [];

  const lines = [
    "#!/usr/bin/env bash",
    ...t.header.map((line) => (line ? `# ${line}` : "#")),
    "",
    "set -euo pipefail",
    "",
    `APP_DIR="${appDir}"`,
    "",
    'if [ -d "$APP_DIR" ]; then',
    // Sin shEscape aquí a propósito: el texto incluye "$APP_DIR" como
    // referencia real a la variable de shell (para que se expanda a la ruta
    // real al imprimirse), no como dato externo que haya que neutralizar.
    `  echo "${t.alreadyExists("$APP_DIR")}"`,
    `  echo "${t.alreadyExistsHint("$APP_DIR")}"`,
    "  exit 1",
    "fi",
    "",
    "if ! command -v docker >/dev/null 2>&1; then",
    `  echo "${shEscape(t.checkingDocker)}"`,
    "  curl -fsSL https://get.docker.com | sh",
    "fi",
    "",
    'mkdir -p "$APP_DIR"',
    `cat > "$APP_DIR/docker-compose.yml" <<'${delimiter}'`,
    finalYaml,
    delimiter,
    "",
    `echo "${shEscape(t.startingContainers)}"`,
    'cd "$APP_DIR"',
    "docker compose up -d",
    "",
    'IP=$(curl -s -4 --max-time 5 ifconfig.me 2>/dev/null || echo "TU_IP")',
    "",
    'echo ""',
    'echo "================================================="',
    `echo "${shEscape(t.successBanner)}"`,
    'echo "-------------------------------------------------"',
    ...summaryLines,
    ...skippedLines,
    'echo "-------------------------------------------------"',
    `echo "${shEscape(t.filesSavedAt)} $APP_DIR"`,
    'echo "================================================="',
    "",
  ];

  return lines.join("\n");
}
