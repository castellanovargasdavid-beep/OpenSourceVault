import { randomBytes } from "crypto";
import type { StackMergeToolSummary } from "@/lib/stack-merge";

const PLACEHOLDER_RE = /change-me[A-Za-z0-9-]*/g;

/**
 * Sustituye cada placeholder `change-me...` del compose fusionado por un
 * secreto aleatorio real, generado en el servidor por request (nunca se
 * reutiliza entre peticiones). Mismo placeholder → mismo secreto dentro de
 * un mismo archivo, para que sigan coincidiendo los pares tipo
 * "POSTGRES_PASSWORD=change-me-db-password # must match DB_..._PASSWORD
 * above" que ya usa el catálogo — igual que el randomizador del cliente en
 * docker-compose-block.tsx, pero aquí con `crypto` de Node porque este
 * módulo solo se ejecuta en el servidor.
 */
export function randomizeSecrets(yaml: string): string {
  const generated = new Map<string, string>();
  return yaml.replace(PLACEHOLDER_RE, (match) => {
    if (!generated.has(match)) generated.set(match, randomBytes(24).toString("hex").slice(0, 32));
    return generated.get(match)!;
  });
}

/** Un delimitador de heredoc que no aparece como línea suelta dentro del propio YAML, por seguridad en profundidad. */
function pickHeredocDelimiter(yaml: string): string {
  let delimiter = "ALTFREESTACK_COMPOSE_EOF";
  const lines = new Set(yaml.split("\n"));
  let suffix = 2;
  while (lines.has(delimiter)) delimiter = `ALTFREESTACK_COMPOSE_EOF_${suffix++}`;
  return delimiter;
}

